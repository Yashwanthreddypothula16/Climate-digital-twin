// Real-time What-If simulation dynamic impact calculator
export function calculateSimulatedClimate(
  base: DistrictClimateData,
  sim: WhatIfSimulationState
): DistrictClimateData {
  const tempShift = sim.temperatureIncrease + (sim.co2Emission * 0.015) - (sim.forestCoverChange * 0.02) + (sim.urbanizationIncrease * 0.03);
  const rainShiftPct = sim.rainfallChange - (sim.forestCoverChange * 0.15) - (sim.co2Emission * 0.05);
  const droughtShiftPct = (sim.temperatureIncrease * 4) - (sim.rainfallChange * 0.6) + (sim.populationGrowth * 0.2);

  const newTemp = +(base.temperature + tempShift).toFixed(1);
  const newRain = +(Math.max(0, base.rainfall24h * (1 + rainShiftPct / 100))).toFixed(1);
  const newAqi = Math.min(500, Math.round(base.aqi + (sim.urbanizationIncrease * 0.6) + (sim.populationGrowth * 0.4) - (sim.forestCoverChange * 0.5)));

  const floodScore = Math.min(100, Math.max(5, Math.round(base.risks.flood.score + (sim.rainfallChange > 0 ? sim.rainfallChange * 0.8 : 0) + (sim.urbanizationIncrease * 0.4))));
  const heatScore = Math.min(100, Math.max(10, Math.round(base.risks.heat.score + (tempShift * 8))));
  const droughtScore = Math.min(100, Math.max(10, Math.round(base.risks.drought.score + (droughtShiftPct * 0.8))));
  const waterStressScore = Math.min(100, Math.max(10, Math.round(base.risks.waterStress.score + (sim.populationGrowth * 0.4) + (tempShift * 4) - (sim.rainfallChange * 0.3))));

  const getRiskLevel = (score: number) => score >= 85 ? 'Critical' : score >= 65 ? 'High' : score >= 40 ? 'Medium' : 'Low';

  return {
    ...base,
    temperature: newTemp,
    rainfall24h: newRain,
    aqi: newAqi,
    lst: +(base.lst + tempShift * 1.1).toFixed(1),
    ndvi: +(Math.max(0.1, Math.min(0.9, base.ndvi + (sim.forestCoverChange * 0.004) - (tempShift * 0.03)))).toFixed(2),
    predictions2030: {
      tempDelta: +(base.predictions2030.tempDelta + tempShift * 0.4).toFixed(1),
      tempConfidence: Math.min(99, base.predictions2030.tempConfidence + 1),
      rainDelta: +(base.predictions2030.rainDelta + rainShiftPct * 0.3).toFixed(0),
      rainConfidence: base.predictions2030.rainConfidence,
      extremeRainDelta: +(base.predictions2030.extremeRainDelta + (tempShift * 3)).toFixed(0),
      extremeRainConfidence: base.predictions2030.extremeRainConfidence,
      droughtDelta: +(base.predictions2030.droughtDelta + (droughtShiftPct * 0.4)).toFixed(0),
      droughtConfidence: base.predictions2030.droughtConfidence,
    },
    risks: {
      flood: { level: getRiskLevel(floodScore), score: floodScore },
      heat: { level: getRiskLevel(heatScore), score: heatScore },
      drought: { level: getRiskLevel(droughtScore), score: droughtScore },
      airQuality: { level: getRiskLevel(newAqi), score: Math.round(newAqi * 0.6) },
      waterStress: { level: getRiskLevel(waterStressScore), score: waterStressScore },
      wildfire: { level: getRiskLevel(Math.round(heatScore * 0.4 + droughtScore * 0.3)), score: Math.round(heatScore * 0.4 + droughtScore * 0.3) },
    }
  };
}

